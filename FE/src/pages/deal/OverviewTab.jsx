import { Bot, Building2, CalendarClock, FileText, Globe2, ListChecks, ShieldAlert, Sparkles, Users } from "lucide-react";
import { Link } from "react-router-dom";
import { diligenceApi, documentsApi } from "../../api/services";
import { Badge, Card, EmptyState, ErrorState, PageLoader, ProgressBar, ProgressRing } from "../../components/ui/primitives";
import { Markdown } from "../../components/ui/Markdown";
import { useAsync } from "../../hooks/useAsync";
import { CATEGORIES, FINDING_TYPES, SEVERITIES } from "../../lib/constants";
import { formatDate, formatMoney, timeAgo } from "../../lib/format";
import { useDeal } from "./DealContext";

const CORE = ["financial", "legal", "tax", "contracts", "hr", "corporate", "commercial", "regulatory", "intellectual_property", "it"];

export default function OverviewTab() {
  const { deal } = useDeal();
  const { data, error, loading, reload } = useAsync(
    () => Promise.all([documentsApi.list(deal.id), diligenceApi.checklist(deal.id), diligenceApi.risks(deal.id), diligenceApi.analysisRuns(deal.id)]),
    [deal.id, deal.updated_at],
  );
  if (loading && !data) return <PageLoader />;
  if (error) return <ErrorState error={error} onRetry={reload} />;
  const [documents, checklist, risks, runs] = data;
  const { stats } = deal;

  const coverage = CORE.map((key) => {
    const docs = documents.filter((d) => d.category === key && d.status === "ready").length;
    const items = checklist.filter((i) => i.category === key);
    const done = items.filter((i) => ["completed", "not_applicable"].includes(i.status)).length;
    const openRisks = risks.filter((r) => r.category === key && ["open", "under_review"].includes(r.status)).length;
    return { key, docs, items: items.length, done, openRisks };
  });

  const topRisks = risks
    .filter((r) => ["open", "under_review"].includes(r.status))
    .sort((a, b) => SEVERITIES[a.severity].rank - SEVERITIES[b.severity].rank)
    .slice(0, 5);
  const lastRun = runs.find((r) => r.status === "completed");
  const checklistPct = stats.checklist_total ? Math.round((100 * stats.checklist_completed) / stats.checklist_total) : 0;

  return (
    <div className="overview-grid">
      <Card className="readiness-card">
        <div className="readiness">
          <ProgressRing value={stats.readiness_score} size={128} stroke={11} sublabel="readiness" />
          <div className="readiness-body">
            <h3>Diligence readiness</h3>
            <p>Composite of checklist completion, workstream coverage and open critical findings.</p>
            <div className="readiness-metrics">
              <div>
                <span>Checklist</span>
                <strong>{checklistPct}%</strong>
                <ProgressBar value={checklistPct} size="sm" tone="info" />
              </div>
              <div>
                <span>Documents indexed</span>
                <strong>
                  {stats.ready_document_count}/{stats.document_count}
                </strong>
                <ProgressBar value={stats.document_count ? (100 * stats.ready_document_count) / stats.document_count : 0} size="sm" tone="success" />
              </div>
              <div>
                <span>Open findings</span>
                <strong className={stats.critical_risk_count ? "text-danger" : ""}>
                  {stats.open_risk_count}
                  {stats.critical_risk_count > 0 && <small> · {stats.critical_risk_count} critical</small>}
                </strong>
              </div>
            </div>
          </div>
        </div>
      </Card>

      <Card title="Deal facts" icon={Building2} className="facts-card">
        <dl className="facts">
          <div>
            <dt>Value</dt>
            <dd>{formatMoney(deal.deal_value, deal.currency, false)}</dd>
          </div>
          <div>
            <dt>
              <Globe2 size={13} /> Target
            </dt>
            <dd>
              {deal.target_name}
              {deal.target_country && <small> · {deal.target_country}</small>}
            </dd>
          </div>
          <div>
            <dt>Industry</dt>
            <dd>{deal.target_industry || "—"}</dd>
          </div>
          <div>
            <dt>
              <CalendarClock size={13} /> Expected close
            </dt>
            <dd>{formatDate(deal.expected_close_date)}</dd>
          </div>
          <div>
            <dt>
              <Users size={13} /> Team
            </dt>
            <dd>{stats.member_count} member(s)</dd>
          </div>
        </dl>
        {deal.description && <p className="facts-description">{deal.description}</p>}
      </Card>

      <Card
        title="Executive summary"
        subtitle={lastRun ? `AI analysis · ${timeAgo(lastRun.completed_at)} · ${lastRun.findings_count} findings` : "Generated by the AI due-diligence analysis"}
        icon={Sparkles}
        className="summary-card"
        actions={<Link to="risks" className="link">Risk register →</Link>}
      >
        {deal.executive_summary ? (
          <Markdown>{deal.executive_summary}</Markdown>
        ) : (
          <EmptyState
            compact
            icon={Bot}
            title="No analysis yet"
            description="Upload documents, then run the AI analysis from the risk register to generate an investment-committee summary."
          />
        )}
      </Card>

      <Card title="Top open findings" icon={ShieldAlert} className="toprisks-card" actions={<Link to="risks" className="link">View all</Link>}>
        {topRisks.length ? (
          <ul className="mini-risks">
            {topRisks.map((risk) => (
              <li key={risk.id}>
                <span className={`sev-bar sev-${risk.severity}`} />
                <div>
                  <strong>{risk.title}</strong>
                  <span>
                    {CATEGORIES[risk.category]?.label} · {FINDING_TYPES[risk.finding_type]?.label}
                  </span>
                </div>
                <Badge tone={SEVERITIES[risk.severity].tone}>{SEVERITIES[risk.severity].label}</Badge>
              </li>
            ))}
          </ul>
        ) : (
          <EmptyState compact icon={ShieldAlert} title="No open findings" />
        )}
      </Card>

      <Card title="Workstream coverage" subtitle="Documents, checklist progress and open findings per workstream" icon={ListChecks} className="coverage-card">
        <div className="coverage-grid">
          {coverage.map(({ key, docs, items, done, openRisks }) => {
            const meta = CATEGORIES[key];
            const Icon = meta.icon;
            return (
              <div key={key} className={`coverage-cell${docs ? "" : " empty"}`}>
                <span className="coverage-icon" style={{ color: meta.color, background: `${meta.color}1a` }}>
                  <Icon size={16} />
                </span>
                <div className="coverage-body">
                  <strong>{meta.label}</strong>
                  <span>
                    <FileText size={12} /> {docs} doc{docs === 1 ? "" : "s"}
                    {openRisks > 0 && <em> · {openRisks} open</em>}
                  </span>
                  {items > 0 && <ProgressBar value={(100 * done) / items} size="sm" tone={docs ? "primary" : "neutral"} />}
                </div>
              </div>
            );
          })}
        </div>
      </Card>
    </div>
  );
}
