import { Filter, SendHorizonal, Square } from "lucide-react";
import { useEffect, useRef, useState } from "react";
import { CATEGORIES } from "../../lib/constants";
import { classNames } from "../../lib/format";

export default function Composer({ onSend, onStop, streaming, disabled, availableCategories, scope, onScopeChange }) {
  const [text, setText] = useState("");
  const [showScope, setShowScope] = useState(false);
  const ref = useRef(null);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    el.style.height = "auto";
    el.style.height = `${Math.min(el.scrollHeight, 180)}px`;
  }, [text]);

  const submit = (event) => {
    event?.preventDefault();
    const question = text.trim();
    if (!question || streaming || disabled) return;
    onSend(question);
    setText("");
  };

  const toggleCategory = (key) =>
    onScopeChange(scope.includes(key) ? scope.filter((k) => k !== key) : [...scope, key]);

  return (
    <form className="composer" onSubmit={submit}>
      {showScope && (
        <div className="composer-scope">
          <span>Search only in:</span>
          {availableCategories.length === 0 && <em>No indexed documents yet</em>}
          {availableCategories.map((key) => (
            <button type="button" key={key} className={classNames("chip sm", scope.includes(key) && "active")} onClick={() => toggleCategory(key)}>
              <i style={{ background: CATEGORIES[key]?.color }} />
              {CATEGORIES[key]?.label}
            </button>
          ))}
          {scope.length > 0 && (
            <button type="button" className="link sm" onClick={() => onScopeChange([])}>
              Clear
            </button>
          )}
        </div>
      )}
      <div className="composer-box">
        <button
          type="button"
          className={classNames("icon-btn ghost", (showScope || scope.length > 0) && "on")}
          onClick={() => setShowScope((v) => !v)}
          title="Limit search to workstreams"
          aria-label="Scope"
        >
          <Filter size={17} />
          {scope.length > 0 && <span className="dot-count">{scope.length}</span>}
        </button>
        <textarea
          ref={ref}
          rows={1}
          value={text}
          onChange={(e) => setText(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && !e.shiftKey) submit(e);
          }}
          placeholder={disabled ? "You have read-only access to this deal" : "Ask about the target — e.g. “What are the change-of-control risks?”"}
          disabled={disabled}
          aria-label="Ask a question"
        />
        {streaming ? (
          <button type="button" className="send-btn stop" onClick={onStop} aria-label="Stop generating">
            <Square size={14} />
          </button>
        ) : (
          <button type="submit" className="send-btn" disabled={!text.trim() || disabled} aria-label="Send">
            <SendHorizonal size={17} />
          </button>
        )}
      </div>
      <p className="composer-hint">
        Answers are generated by Gemini from your data room only, with numbered citations. Verify material findings against the source.
      </p>
    </form>
  );
}
